const PER_TEAM: Record<Role, number> = { P: 3, D: 8, C: 8, A: 5 };

/**
 * Real notable players plus deterministic generated depth players so every
 * Serie A club fields a full squad (needed to complete 8×25 rosters in demo).
 */
export function buildSamplePlayers(): PlayerInput[] {
  const players: PlayerInput[] = REAL.map(([displayName, teamName, role, q, fvm], i) => ({
    externalId: `sample-${i + 1}`,
    displayName,
    teamName,
    teamAbbr: teamAbbreviation(teamName),
    role,
    mantraRoles: [],
    initialQuotation: q,
    currentQuotation: q,
    fvm,
  }));

  let surnameIdx = 0;
  let extId = REAL.length + 1;
  const counts = new Map<string, number>();
  for (const p of players) counts.set(`${p.teamName}:${p.role}`, (counts.get(`${p.teamName}:${p.role}`) ?? 0) + 1);

  for (const team of TEAMS) {
    for (const role of ["P", "D", "C", "A"] as Role[]) {
      const have = counts.get(`${team}:${role}`) ?? 0;
      for (let n = have; n < PER_TEAM[role]; n++) {
        const surname = SURNAMES[surnameIdx % SURNAMES.length];
        const suffix = Math.floor(surnameIdx / SURNAMES.length);
        surnameIdx++;
        const q = role === "P" ? 1 + (n % 3) : 1 + ((n + surnameIdx) % 5);
        players.push({
          externalId: `sample-${extId++}`,
          displayName: suffix > 0 ? `${surname} ${["II", "III", "IV"][suffix - 1] ?? suffix}` : surname,
          teamName: team,
          teamAbbr: teamAbbreviation(team),
          role,
          mantraRoles: [],
          initialQuotation: q,
          currentQuotation: q,
          fvm: q * 4,
        });
      }
    }
  }
  return players;
}
